package org.openfilz.dms.service.language;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.function.UnaryOperator;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import java.util.zip.ZipOutputStream;

/**
 * Reads and sets the proofing language of a Word (.docx) document — the {@code <w:lang w:val>}
 * that Word and OnlyOffice spell-check the text against.
 * <p>
 * A document that declares none is checked against the editor's language, so a French text
 * generated by a script opens in OnlyOffice full of red underlines. {@link #inspect} reports the
 * declared language and a sample of the text; {@link #rewrite} writes the language into the
 * document defaults ({@code w:docDefaults} of {@code styles.xml}) and into the default paragraph
 * style (Normal), and moves every run that carried the previous language to the new one — runs in a
 * third language (a quote) are left alone.
 * <p>
 * Why the Normal style too: OnlyOffice's editor writes the document defaults back without the
 * language when it is {@code en-US} (its own built-in default), so the first save after an edit
 * erased an English language set here and the question came back on the next opening. It keeps a
 * language held by a style (checked with docbuilder 9.4), and the Normal style also wins over a
 * stale default in Word.
 * <p>
 * The XML is edited as text, not re-serialised, so every other byte of the parts is kept as
 * Word wrote it. Only the {@code w:} prefix is understood (what Word, LibreOffice, OnlyOffice and
 * the docx libraries all write); a document using another prefix reports no declared language
 * and is not rewritten.
 * <p>
 * A part is read in a time proportional to its length, whatever it holds: it comes from whoever
 * uploaded the document and may inflate to {@link #MAX_PART_BYTES}. Two rules keep it so. A tag is
 * matched with {@code [^<>]*}, never {@code [^>]*}, so a tag that is not closed stops at the next
 * one instead of running to the end of the part. An element is found by {@link #first}, never by a
 * {@code <x>(.*?)</x>} pattern, which looks for the closing tag again from every opening one.
 */
public final class DocxLanguage {

    static final String STYLES = "word/styles.xml";
    static final String DOCUMENT = "word/document.xml";

    /** Parts whose runs may carry a {@code w:lang}. */
    private static final Pattern TEXT_PARTS = Pattern.compile(
            "word/(document|styles|header\\d*|footer\\d*|footnotes|endnotes|comments)\\.xml");

    private static final Pattern LANG = Pattern.compile("<w:lang\\b[^<>]*?/?>");
    private static final Pattern VAL = Pattern.compile("\\bw:val=\"([^\"]*)\"");
    // Opening (or self-closing) tags, each with its closing tag: see first()
    private static final Pattern DOC_DEFAULTS = Pattern.compile("<w:docDefaults\\b[^<>]*>");
    private static final String DOC_DEFAULTS_END = "</w:docDefaults>";
    private static final Pattern RPR_DEFAULT = Pattern.compile("<w:rPrDefault\\b[^<>]*>");
    private static final String RPR_DEFAULT_END = "</w:rPrDefault>";
    private static final Pattern RPR = Pattern.compile("<w:rPr\\b[^<>]*>");
    private static final String RPR_END = "</w:rPr>";
    /** Elements that follow {@code w:lang} in a run's properties (schema order of CT_RPr). */
    private static final Pattern AFTER_LANG = Pattern.compile("<w:(eastAsianLayout|specVanish|oMath)\\b");
    private static final Pattern STYLES_OPEN = Pattern.compile("<w:styles\\b[^<>]*>");
    /** The tag of the default paragraph style (Normal): {@code w:type="paragraph"} and {@code w:default} on. */
    private static final Pattern DEFAULT_PARAGRAPH_STYLE = Pattern.compile(
            "<w:style\\b(?=[^<>]*\\bw:type=\"paragraph\")(?=[^<>]*\\bw:default=\"(?:1|true|on)\")[^<>]*>");
    private static final String STYLE_END = "</w:style>";
    /** Elements that follow {@code w:rPr} in a style (schema order of CT_Style). */
    private static final Pattern AFTER_STYLE_RPR = Pattern.compile("<w:(tblPr|trPr|tcPr|tblStylePr)\\b");
    private static final Pattern TEXT = Pattern.compile("<w:t(?:\\s[^<>]*)?>([^<]*)</w:t>|</w:p>|<w:tab\\s*/>|<w:br\\s*/>");
    private static final Pattern ENTITY = Pattern.compile("&(#x[0-9a-fA-F]+|#\\d+|amp|lt|gt|quot|apos);");

    /** Text kept for the language guess; a few pages are plenty. */
    static final int MAX_TEXT_CHARS = 20_000;

    /** An XML part larger than this once inflated is refused rather than read into memory. */
    static final int MAX_PART_BYTES = 64 * 1024 * 1024;

    /**
     * @param defaultLanguage       the document default ({@code w:docDefaults}), or null
     * @param styleLanguage         the language of the default paragraph style (Normal), or null
     * @param defaultParagraphStyle the style part has a default paragraph style
     * @param languages             how many {@code w:lang w:val} carry each language, across the text parts
     * @param text                  the beginning of the body text
     */
    public record Inspection(String defaultLanguage, String styleLanguage, boolean defaultParagraphStyle,
                             Map<String, Integer> languages, String text, boolean rewritable) {

        /**
         * The Normal style's, else the default, else the language most runs carry, else null. The
         * style first: it overrides the default for every paragraph that names no other style, so
         * it is the language the text is checked against when the two differ (Word writes such
         * documents: an {@code en-GB} default under a {@code fr-FR} Normal style).
         */
        public String declaredLanguage() {
            if (styleLanguage != null) {
                return styleLanguage;
            }
            if (defaultLanguage != null) {
                return defaultLanguage;
            }
            return languages.entrySet().stream()
                    .max(Map.Entry.comparingByValue())
                    .map(Map.Entry::getKey)
                    .orElse(null);
        }
    }

    private DocxLanguage() {
    }

    public static Inspection inspect(Path docx) throws IOException {
        try (ZipFile zip = new ZipFile(docx.toFile())) {
            String styles = read(zip, STYLES);
            String document = read(zip, DOCUMENT);
            if (document == null) {
                throw new IOException("Not a Word document: no " + DOCUMENT);
            }
            Map<String, Integer> languages = new HashMap<>();
            var entries = zip.entries();
            while (entries.hasMoreElements()) {
                ZipEntry entry = entries.nextElement();
                if (TEXT_PARTS.matcher(entry.getName()).matches()) {
                    String xml = entry.getName().equals(DOCUMENT) ? document
                            : entry.getName().equals(STYLES) ? styles : read(zip, entry.getName());
                    countLanguages(xml, languages);
                }
            }
            Element normal = styles == null ? null : first(DEFAULT_PARAGRAPH_STYLE, STYLE_END, styles);
            return new Inspection(defaultLanguage(styles), styleLanguage(styles, normal), normal != null,
                    Collections.unmodifiableMap(languages),
                    text(document), styles != null && STYLES_OPEN.matcher(styles).find());
        }
    }

    /**
     * Copies {@code source} to {@code target} with {@code language} as the document default and
     * every {@code w:lang w:val} of the same base language as {@code previous} (e.g. {@code en-US},
     * {@code en-GB} when previous is {@code en-US}) set to {@code language} — a regional change
     * ({@code en-US} → {@code en-GB}) moves the runs too, so the document ends up uniformly in
     * {@code language}. For Arabic the complex-script language ({@code w:bidi}) is set too.
     *
     * @param previous the language the document declared before, or null
     * @throws IOException when the document has no {@code styles.xml} to hold the default
     */
    public static void rewrite(Path source, Path target, String language, String previous) throws IOException {
        String previousBase = previous == null ? null : base(previous);
        try (ZipFile zip = new ZipFile(source.toFile());
             OutputStream out = Files.newOutputStream(target);
             ZipOutputStream zipOut = new ZipOutputStream(out)) {
            if (zip.getEntry(STYLES) == null) {
                throw new IOException("Word document without " + STYLES);
            }
            var entries = zip.entries();
            while (entries.hasMoreElements()) {
                ZipEntry entry = entries.nextElement();
                ZipEntry copy = new ZipEntry(entry.getName());
                if (entry.getLastModifiedTime() != null) {
                    copy.setLastModifiedTime(entry.getLastModifiedTime());
                }
                zipOut.putNextEntry(copy);
                if (TEXT_PARTS.matcher(entry.getName()).matches()) {
                    String xml = read(zip, entry.getName());
                    UnaryOperator<String> relabel = previousBase == null
                            ? UnaryOperator.identity()
                            : x -> relabel(x, previousBase, language);
                    String updated = relabel.apply(xml);
                    if (entry.getName().equals(STYLES)) {
                        updated = withDefaultStyleLanguage(withDefaultLanguage(updated, language), language);
                    }
                    zipOut.write(updated.getBytes(StandardCharsets.UTF_8));
                } else {
                    try (InputStream in = zip.getInputStream(entry)) {
                        in.transferTo(zipOut);
                    }
                }
                zipOut.closeEntry();
            }
        }
    }

    /** {@code fr-FR} → {@code fr}. */
    public static String base(String language) {
        int dash = language.indexOf('-');
        return (dash < 0 ? language : language.substring(0, dash)).toLowerCase(Locale.ROOT);
    }

    // ── reading ─────────────────────────────────────────────────────────────

    /** Where an element lies in a part; {@code bodyStart} is -1 for a self-closing one. */
    private record Element(int start, int bodyStart, int bodyEnd, int end) {

        boolean selfClosing() {
            return bodyStart < 0;
        }

        /** What the element holds: nothing for a self-closing one. */
        String body(String xml) {
            return selfClosing() ? "" : xml.substring(bodyStart, bodyEnd);
        }
    }

    /**
     * The first element of {@code xml} whose tag matches {@code tag}, or null. Its closing tag is
     * looked for once, from that tag: when there is none, no later tag has one either, so there is
     * nothing more to try.
     */
    private static Element first(Pattern tag, String closingTag, String xml) {
        Matcher open = tag.matcher(xml);
        if (!open.find()) {
            return null;
        }
        if (xml.charAt(open.end() - 2) == '/') {
            return new Element(open.start(), -1, -1, open.end());
        }
        int close = xml.indexOf(closingTag, open.end());
        return close < 0 ? null : new Element(open.start(), open.end(), close, close + closingTag.length());
    }

    static String defaultLanguage(String styles) {
        Element defaults = styles == null ? null : first(DOC_DEFAULTS, DOC_DEFAULTS_END, styles);
        return defaults == null ? null : firstLanguage(defaults.body(styles));
    }

    /** The language of the default paragraph style, or null. */
    static String styleLanguage(String styles) {
        return styles == null ? null : styleLanguage(styles, first(DEFAULT_PARAGRAPH_STYLE, STYLE_END, styles));
    }

    private static String styleLanguage(String styles, Element style) {
        if (style == null) {
            return null;
        }
        String body = style.body(styles);
        Element rPr = first(RPR, RPR_END, body);
        return rPr == null ? null : firstLanguage(rPr.body(body));
    }

    /** The first {@code w:lang w:val} of {@code xml} that names a language, or null. */
    private static String firstLanguage(String xml) {
        Matcher lang = LANG.matcher(xml);
        while (lang.find()) {
            Matcher val = VAL.matcher(lang.group());
            if (val.find() && !val.group(1).isBlank()) {
                return val.group(1);
            }
        }
        return null;
    }

    private static void countLanguages(String xml, Map<String, Integer> languages) {
        if (xml == null) {
            return;
        }
        Matcher lang = LANG.matcher(xml);
        while (lang.find()) {
            Matcher val = VAL.matcher(lang.group());
            if (val.find() && !val.group(1).isBlank()) {
                languages.merge(val.group(1), 1, Integer::sum);
            }
        }
    }

    static String text(String document) {
        StringBuilder text = new StringBuilder();
        Matcher m = TEXT.matcher(document);
        while (m.find() && text.length() < MAX_TEXT_CHARS) {
            text.append(m.group(1) != null ? unescape(m.group(1)) : " ");
        }
        return text.length() > MAX_TEXT_CHARS ? text.substring(0, MAX_TEXT_CHARS) : text.toString();
    }

    private static String unescape(String xml) {
        if (xml.indexOf('&') < 0) {
            return xml;
        }
        return ENTITY.matcher(xml).replaceAll(m -> Matcher.quoteReplacement(switch (m.group(1)) {
            case "amp" -> "&";
            case "lt" -> "<";
            case "gt" -> ">";
            case "quot" -> "\"";
            case "apos" -> "'";
            default -> {
                String code = m.group(1);
                try {
                    int cp = code.startsWith("#x") ? Integer.parseInt(code.substring(2), 16) : Integer.parseInt(code.substring(1));
                    yield Character.isValidCodePoint(cp) ? new String(Character.toChars(cp)) : " ";
                } catch (NumberFormatException e) {
                    yield " ";
                }
            }
        }));
    }

    // ── writing ─────────────────────────────────────────────────────────────

    /** Sets {@code w:val} of the {@code w:lang} elements whose language has base {@code previousBase}. */
    static String relabel(String xml, String previousBase, String language) {
        return LANG.matcher(xml).replaceAll(m -> {
            String element = m.group();
            Matcher val = VAL.matcher(element);
            if (val.find() && !val.group(1).isBlank() && base(val.group(1)).equals(previousBase)) {
                return Matcher.quoteReplacement(val.replaceFirst("w:val=\"" + language + "\""));
            }
            return Matcher.quoteReplacement(element);
        });
    }

    /** {@code styles.xml} with {@code language} as the document default, creating the elements it lacks. */
    static String withDefaultLanguage(String styles, String language) {
        String lang = langElement(language);
        Element defaults = first(DOC_DEFAULTS, DOC_DEFAULTS_END, styles);
        if (defaults == null) {
            Matcher open = STYLES_OPEN.matcher(styles);
            if (!open.find()) {
                throw new IllegalArgumentException("styles.xml without <w:styles>");
            }
            return styles.substring(0, open.end())
                    + "<w:docDefaults><w:rPrDefault><w:rPr>" + lang + "</w:rPr></w:rPrDefault></w:docDefaults>"
                    + styles.substring(open.end());
        }
        String body = defaults.body(styles);
        String newBody;
        Element rPrDefault = first(RPR_DEFAULT, RPR_DEFAULT_END, body);
        if (rPrDefault == null) {
            // rPrDefault comes first in docDefaults (before pPrDefault)
            newBody = "<w:rPrDefault><w:rPr>" + lang + "</w:rPr></w:rPrDefault>" + body;
        } else {
            String rPrDefaultBody = rPrDefault.body(body);
            Element rPr = first(RPR, RPR_END, rPrDefaultBody);
            String newRPrDefaultBody;
            if (rPr == null) {
                newRPrDefaultBody = "<w:rPr>" + lang + "</w:rPr>" + rPrDefaultBody;
            } else {
                newRPrDefaultBody = rPrDefaultBody.substring(0, rPr.start())
                        + "<w:rPr>" + withLang(rPr.body(rPrDefaultBody), language) + "</w:rPr>"
                        + rPrDefaultBody.substring(rPr.end());
            }
            newBody = body.substring(0, rPrDefault.start())
                    + "<w:rPrDefault>" + newRPrDefaultBody + "</w:rPrDefault>"
                    + body.substring(rPrDefault.end());
        }
        return styles.substring(0, defaults.start())
                + "<w:docDefaults>" + newBody + "</w:docDefaults>"
                + styles.substring(defaults.end());
    }

    /**
     * {@code styles.xml} with {@code language} on the default paragraph style, creating its run
     * properties if needed. Unchanged when the part has no default paragraph style: the document
     * defaults then carry the language alone.
     */
    static String withDefaultStyleLanguage(String styles, String language) {
        Element style = first(DEFAULT_PARAGRAPH_STYLE, STYLE_END, styles);
        if (style == null) {
            return styles;
        }
        // <w:style .../> is opened to hold the run properties
        String open = style.selfClosing()
                ? styles.substring(style.start(), style.end() - 2).stripTrailing() + ">"
                : styles.substring(style.start(), style.bodyStart());
        String body = style.body(styles);
        Element rPr = first(RPR, RPR_END, body);
        String newBody;
        if (rPr != null) {
            newBody = body.substring(0, rPr.start()) + "<w:rPr>" + withLang(rPr.body(body), language) + "</w:rPr>"
                    + body.substring(rPr.end());
        } else {
            Matcher after = AFTER_STYLE_RPR.matcher(body);
            int at = after.find() ? after.start() : body.length();
            newBody = body.substring(0, at) + "<w:rPr>" + langElement(language) + "</w:rPr>" + body.substring(at);
        }
        return styles.substring(0, style.start()) + open + newBody + STYLE_END + styles.substring(style.end());
    }

    /** Run properties with their {@code w:lang} set to {@code language}, in schema order. */
    private static String withLang(String props, String language) {
        Matcher existing = LANG.matcher(props);
        if (existing.find()) {
            String element = existing.group();
            Matcher val = VAL.matcher(element);
            String updated = val.find()
                    ? val.replaceFirst(Matcher.quoteReplacement("w:val=\"" + language + "\""))
                    : element.replaceFirst("<w:lang\\b", Matcher.quoteReplacement("<w:lang w:val=\"" + language + "\""));
            if ("ar".equals(base(language)) && !updated.contains("w:bidi=")) {
                updated = updated.replaceFirst("<w:lang\\b", Matcher.quoteReplacement("<w:lang w:bidi=\"" + language + "\""));
            }
            return props.substring(0, existing.start()) + updated + props.substring(existing.end());
        }
        Matcher after = AFTER_LANG.matcher(props);
        int at = after.find() ? after.start() : props.length();
        return props.substring(0, at) + langElement(language) + props.substring(at);
    }

    private static String langElement(String language) {
        return "ar".equals(base(language))
                ? "<w:lang w:val=\"" + language + "\" w:bidi=\"" + language + "\"/>"
                : "<w:lang w:val=\"" + language + "\"/>";
    }

    private static String read(ZipFile zip, String name) throws IOException {
        ZipEntry entry = zip.getEntry(name);
        if (entry == null) {
            return null;
        }
        try (InputStream in = zip.getInputStream(entry)) {
            byte[] bytes = in.readNBytes(MAX_PART_BYTES + 1);
            if (bytes.length > MAX_PART_BYTES) {
                throw new IOException("Part " + name + " is larger than " + MAX_PART_BYTES + " bytes");
            }
            return new String(bytes, StandardCharsets.UTF_8);
        }
    }
}
